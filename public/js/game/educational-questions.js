/**
 * Validates question bank structure and ensures 100% integrity
 * @param {Array} bank 
 * @returns {{ valid: boolean, count: number, errors: string[] }}
 */
export function validateQuestionBank(bank = EDUCATIONAL_QUESTIONS) {
  const errors = [];
  if (!Array.isArray(bank) || bank.length === 0) {
    return { valid: false, count: 0, errors: ['Question bank is empty or not an array'] };
  }

  bank.forEach((q, idx) => {
    if (!q.id) errors.push(`Question at index ${idx} missing id`);
    if (!q.question || typeof q.question !== 'string') errors.push(`Question ${q.id || idx} missing question text`);
    if (!Array.isArray(q.options) || q.options.length < 2) errors.push(`Question ${q.id || idx} options invalid`);
    if (!q.correctAnswer) errors.push(`Question ${q.id || idx} missing correctAnswer`);
    if (q.options && !q.options.includes(q.correctAnswer)) {
      errors.push(`Question ${q.id} correctAnswer "${q.correctAnswer}" not in options`);
    }
  });

  return {
    valid: errors.length === 0,
    count: bank.length,
    errors
  };
}

/**
 * Question Deck Manager:
 * Provides shuffled questions without repeating within the same run until the bank is exhausted.
 */
export class QuestionDeck {
  constructor(questions = EDUCATIONAL_QUESTIONS) {
    this.source = [...questions];
    this.deck = [];
    this.history = [];
    this._refill();
  }

  _refill() {
    this.deck = [...this.source];
    // Fisher-Yates shuffle
    for (let i = this.deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [this.deck[i], this.deck[j]] = [this.deck[j], this.deck[i]];
    }
  }

  /**
   * Draws the next random unrepeated question. Automatically reshuffles if exhausted.
   * @returns {object} question object with shuffled options
   */
  drawNextQuestion() {
    if (this.deck.length === 0) {
      this._refill();
    }
    const q = this.deck.pop();
    this.history.push(q);

    // Return a clone with randomized option display ordering
    const shuffledOptions = [...q.options];
    for (let i = shuffledOptions.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [shuffledOptions[i], shuffledOptions[j]] = [shuffledOptions[j], shuffledOptions[i]];
    }

    return {
      ...q,
      shuffledOptions
    };
  }

  /**
   * Draws a level set of questions (e.g. 5 questions)
   * @param {number} count 
   * @returns {object[]}
   */
  drawLevelQuestions(count = 5) {
    const list = [];
    for (let i = 0; i < count; i++) {
      list.push(this.drawNextQuestion());
    }
    return list;
  }

  reset() {
    this.history = [];
    this._refill();
  }
}

